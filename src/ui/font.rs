/// RGBA8 bitmap of the whole font texture.
pub fn build_texture() -> Vec<u8> {
    let mut px = vec![0u8; (TEX_W * TEX_H * 4) as usize];
    for (i, g) in GLYPHS.iter().enumerate() {
        let cx = (i as u32 % COLS) * CELL;
        let cy = (i as u32 / COLS) * CELL;
        for (row, line) in g.split('|').enumerate() {
            for (col, ch) in line.chars().enumerate() {
                if ch == '#' {
                    let x = cx + col as u32;
                    let y = cy + row as u32;
                    let o = ((y * TEX_W + x) * 4) as usize;
                    px[o] = 255;
                    px[o + 1] = 255;
                    px[o + 2] = 255;
                    px[o + 3] = 255;
                }
            }
        }
    }
    px
}

/// UV rectangle (u0, v0, u1, v1) of a character's 8x8 cell.
pub fn glyph_uv(c: char) -> [f32; 4] {
    let code = c as u32;
    let idx = if (32..127).contains(&code) { code - 32 } else { '?' as u32 - 32 };
    let cx = (idx % COLS) as f32;
    let cy = (idx / COLS) as f32;
    let cw = CELL as f32 / TEX_W as f32;
    let ch = CELL as f32 / TEX_H as f32;
    [cx * cw, cy * ch, (cx + 1.0) * cw, (cy + 1.0) * ch]
}

/// Advance in pixels at scale 1 (glyph + 1px gap).
pub const ADVANCE: f32 = 6.0;
pub const LINE_HEIGHT: f32 = 9.0;

pub fn text_width(s: &str, scale: f32) -> f32 {
    s.chars().count() as f32 * ADVANCE * scale
}

pub fn upload(device: &wgpu::Device, queue: &wgpu::Queue) -> wgpu::TextureView {
    let tex = device.create_texture(&wgpu::TextureDescriptor {
        label: Some("font"),
        size: wgpu::Extent3d { width: TEX_W, height: TEX_H, depth_or_array_layers: 1 },
        mip_level_count: 1,
        sample_count: 1,
        dimension: wgpu::TextureDimension::D2,
        format: wgpu::TextureFormat::Rgba8Unorm,
        usage: wgpu::TextureUsages::TEXTURE_BINDING | wgpu::TextureUsages::COPY_DST,
        view_formats: &[],
    });
    queue.write_texture(
        wgpu::ImageCopyTexture { texture: &tex, mip_level: 0, origin: wgpu::Origin3d::ZERO, aspect: wgpu::TextureAspect::All },
        &build_texture(),
        wgpu::ImageDataLayout { offset: 0, bytes_per_row: Some(TEX_W * 4), rows_per_image: Some(TEX_H) },
        wgpu::Extent3d { width: TEX_W, height: TEX_H, depth_or_array_layers: 1 },
    );
    tex.create_view(&Default::default())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_glyph_is_five_by_seven() {
        for (i, g) in GLYPHS.iter().enumerate() {
            let rows: Vec<&str> = g.split('|').collect();
            assert_eq!(rows.len(), 7, "glyph {} ({:?}) has {} rows", i, (i as u8 + 32) as char, rows.len());
            for r in rows {
                assert_eq!(r.len(), 5, "glyph {} row {:?}", i, r);
            }
        }
        let tex = build_texture();
        assert_eq!(tex.len(), (TEX_W * TEX_H * 4) as usize);
        assert!(tex.iter().skip(3).step_by(4).any(|a| *a == 255));
    }
}
